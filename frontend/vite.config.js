import vue from '@vitejs/plugin-vue'
import { defineConfig } from 'vite'

// https://vite.dev/config/
export default defineConfig({
  plugins: [vue()],

  // ==========================================================================
  // 开发服务器配置
  // ==========================================================================
  server: {
    // 【代理是什么】一句大白话：
    //   浏览器请求 http://localhost:5173/api/plans
    //   → Vite 开发服务器收到后，偷偷转发给 http://127.0.0.1:8000/api/plans
    //   → 拿到后端响应再原样返回给浏览器
    //
    // 【为什么要这样做】浏览器有"同源策略"：5173 和 8000 端口不同就算跨域，
    //   直接请求会被浏览器拦下（CORS 报错）。
    //   配了代理后，前端代码里只写 "/api/plans"（相对路径），
    //   浏览器认为自己在请求 5173 自己，压根不存在跨域问题。
    //
    // 【企业里对应什么】这就是"Nginx 反向代理"的本机简化版。
    //   生产的架构通常是：
    //       浏览器 → Nginx(/api 转发) → 后端服务 → 数据库
    //   你在 Vite 里配的这段，等于提前把生产环境的转发逻辑在本机跑通了。
    //   这也是为什么前端代码里要写相对路径 "/api"，而不是写死
    //   "http://127.0.0.1:8000" —— 写死的话，上线后域名一换，全站请求全挂。
    proxy: {
      '/api': {
        target: 'http://127.0.0.1:8000', // 后端真实地址（uvicorn 默认端口）
        changeOrigin: true,              // 把转发请求的 Host 头改成目标地址，
                                         // 避免后端按 Host 校验来源时误判
      },
    },
  },

  // 说明：这里【故意不配】生产构建的 base、build.outDir 等，
  // 那些等做到 Docker/Nginx 部署时再配，现在配了也没法验证。
  // 一次只解决一个问题，避免"写了但没验证过"的配置堆在文件里。
})
