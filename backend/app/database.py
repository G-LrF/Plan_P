"""
数据库连接层 —— 创建连接池、提供会话、管理表的创建

【这一层的职责只有一个：管好"怎么连数据库"。】
    它不应该懂任何业务逻辑（不懂什么是"计划"），
    也不应该出现在路由里被直接调用。业务层通过它拿 Session，仅此而已。

==========================================================================
【核心概念：Session 是什么？为什么必须有它】
--------------------------------------------------------------------------
    把数据库想象成一个仓库：
      Engine  = 仓库的地址 + 每天派几辆卡车去拉货（连接池）
      Session = 你派出去办事的那一辆车（一次对话）

    一个请求进来 → 开一个 Session → 做若干次查询/修改 → 关闭 Session

    【为什么不能每个查询都新建一个连接】
      MySQL 建立一个 TCP 连接要握手、认证，成本大约几毫秒。
      如果每个查询都新建连接，高并发时会瞬间把数据库的连接数打满，
      报错 "Too many connections"，然后整个服务不可用。
      连接池的作用就是"复用"，用完还回去而不是销毁。

    【为什么 Session 要 finally 关闭 / 用 with 管理】
      不关闭 = 连接不归还 = 连接池被占满 = 后面的请求全部超时。
      这是线上最常见的故障原因之一，且症状很迷惑（服务看起来在跑，但所有请求超时）。
==========================================================================
"""

from collections.abc import Generator

from sqlalchemy import create_engine
from sqlalchemy.orm import Session, sessionmaker

from app.config import get_settings

# 读取配置
settings = get_settings()


# ---------------------------------------------------------------------------
# Engine：连接池的管理者
# ---------------------------------------------------------------------------
engine = create_engine(
    settings.database_url,

    # ------------------------------------------------------------------
    # pool_pre_ping：连接还活着吗？
    # ------------------------------------------------------------------
    # 【这个参数为什么重要】
    #   数据库连接放久了会被 MySQL 服务端主动断开（默认 8 小时，wait_timeout）。
    #   连接池里存着的却是"已死的连接"，取出来用就会报：
    #       (2006, 'MySQL server has gone away')
    #
    #   这个报错的特点是：平时都好好的，隔一夜或中午休息回来第一次请求必崩，
    #   而且重启服务又好了 —— 极难排查。
    #
    #   pool_pre_ping=True 会在每次取连接前先 ping 一下，
    #   发现断了就自动重建。代价是每次取连接多一次极轻量的往返。
    #   【结论】生产环境必开，几乎没人会关它。
    pool_pre_ping=True,

    # ------------------------------------------------------------------
    # pool_recycle：连接最多复用多久（秒）
    # ------------------------------------------------------------------
    # 主动在连接被服务端断开之前将它回收重建，比依赖 pre_ping 更保险（双保险）。
    # 3600 秒 = 1 小时，比 MySQL 默认的 8 小时 wait_timeout 短得多。
    pool_recycle=3600,

    # ------------------------------------------------------------------
    # pool_size / max_overflow：连接池大小
    # ------------------------------------------------------------------
    # pool_size=5       ：池子里常驻 5 个连接
    # max_overflow=10   ：高峰期最多再临时借 10 个（用完会销毁）
    # 所以本服务最多同时使用 15 个连接。
    #
    # 【怎么定这个数】
    #   不是越大越好。MySQL 的连接数上限由 max_connections 控制（默认 151），
    #   多个服务共用时必须分摊。经验公式：连接数 ≈ CPU核数 × 2 + 磁盘数。
    #   小项目 5~10 足够，等有真实压力再按监控数据调整。
    pool_size=5,
    max_overflow=10,

    # ------------------------------------------------------------------
    # echo：要不要把执行的 SQL 打印出来
    # ------------------------------------------------------------------
    # 开启后控制台会打印每条 SQL，调试时极其有用。
    # 但生产环境千万别开 —— 日志量会暴涨，还可能把敏感数据打到日志里。
    # 所以这里绑到 DEBUG 配置上：本地开着方便学，生产自动关。
    echo=settings.debug,
)


# ---------------------------------------------------------------------------
# SessionLocal：会话工厂
# ---------------------------------------------------------------------------
# 【为什么叫"工厂"】
#   它本身不是 Session，而是一个"造 Session 的函数"。
#   每调用一次 SessionLocal() 就得到一个全新的独立会话。
#
# autocommit=False 的含义：
#   默认不自动提交。你改了数据必须手动 session.commit() 才算数。
#   这样多个操作可以组成一个事务 —— 要么全成功，要么全失败回滚。
#   【为什么不能自动提交】想想转账：扣钱和加钱必须一起成功，
#   如果每条语句自动提交，中间崩了就会只扣不加。
session_factory = sessionmaker(
    bind=engine,
    autocommit=False,
    autoflush=False,
)


def get_db() -> Generator[Session, None, None]:
    """FastAPI 的依赖注入函数：每个请求拿一个 Session，用完自动关闭。

    【为什么写成生成器（yield）而不是 return】
        FastAPI 看到 yield 就知道这是个"依赖"：
          1. 请求进来时执行到 yield，把 Session 交出去
          2. 请求处理完（无论成功还是抛异常），回来继续执行 finally

        所以 finally 里的 close() 一定会执行 —— 这是保证连接不泄漏的关键。

    【在路由里怎么用】
        @router.get("/plans")
        def get_plans(db: Session = Depends(get_db)):
            ...

        你完全不用管 Session 的创建和关闭，FastAPI 帮你管。

    【注意】这里没有 commit。
        查询不需要 commit，而写操作（增删改）必须由业务代码显式 commit，
        因为"什么时候算一次完整的事务"是业务决定的，不能由框架替你猜。
    """
    db = session_factory()
    try:
        yield db
    finally:
        db.close()


def init_db() -> None:
    """初始化数据库：根据 models.py 的定义创建所有表。

    【为什么用代码建表，而不是手写 CREATE TABLE】
        1. 唯一事实来源：表结构写在 models.py，代码就是文档
        2. 换环境零成本：新电脑/服务器上启动程序，表自动建好
        3. 不会漏：手动建表时，换个环境少建一个索引根本没人发现

    【create_all 的行为要知道】
        - 只创建"不存在的表"，已存在的表【不会】被修改
        - 所以它不能用来做表结构升级（加字段必须用 Alembic 迁移）

    【为什么在这里 import models】
        为了让 SQLAlchemy 知道有哪些模型类。
        metadata 是注册表，只有类被 import 过，才会登记进去。
        写在函数内部 import 是为了避免循环导入
        （models.py 会 import database.py 拿 Base）。
    """
    from app import models  # noqa: F401  （这行只为触发模型注册，不直接使用）

    models.Base.metadata.create_all(bind=engine)
